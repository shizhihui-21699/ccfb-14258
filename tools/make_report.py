#!/usr/bin/env python3
"""Generate report/REPORT.md tables from results/experiments.log.

Kept separate from the hand-written analysis so every number in the tables is
copied mechanically from the C++ experiment output (no transcription errors).
Run: python3 tools/make_report.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOG = ROOT / "results" / "experiments.log"
OUT = ROOT / "report" / "tables.md"


def parse(log_text):
    rows = []
    for line in log_text.splitlines():
        if line.startswith("CSV,"):
            rows.append(line[4:].split(","))
    return rows


def fmt_pct(x):
    return f"{100*float(x):.1f}%"


def main():
    if not LOG.exists():
        sys.exit(f"missing {LOG}; run build/experiments all > results/experiments.log")
    rows = parse(LOG.read_text())
    by_kind = {}
    for r in rows:
        by_kind.setdefault(r[0], []).append(r)

    out = []
    out.append("<!-- generated by tools/make_report.py; do not edit by hand -->\n")

    # Temperature
    if "temp" in by_kind:
        out.append("### Unlock success vs temperature (3.3 V, fresh silicon, default t=32)\n")
        out.append("| Temperature (C) | Success |\n|---:|---:|")
        for r in by_kind["temp"]:
            out.append(f"| {float(r[1]):+.0f} | {fmt_pct(r[2])} ({r[3]}/{r[4]}) |")
        out.append("")

    # Voltage
    if "volt" in by_kind:
        out.append("### Unlock success vs supply voltage (25 C)\n")
        out.append("| Supply (V) | Success |\n|---:|---:|")
        for r in by_kind["volt"]:
            out.append(f"| {float(r[1]):.2f} | {fmt_pct(r[2])} ({r[3]}/{r[4]}) |")
        out.append("")

    # Joint hot + low voltage
    if "joint" in by_kind:
        out.append("### Combined hot + low-voltage corners\n")
        out.append("| Temperature (C) | Supply (V) | Success |\n|---:|---:|---:|")
        for r in by_kind["joint"]:
            out.append(f"| {float(r[1]):+.0f} | {float(r[2]):.2f} | {fmt_pct(r[3])} |")
        out.append("")

    # Aging
    if "age" in by_kind:
        out.append("### Unlock success vs silicon age (25 C, enrolled fresh)\n")
        out.append("| Age (years) | Success |\n|---:|---:|")
        for r in by_kind["age"]:
            out.append(f"| {float(r[1]):.0f} | {fmt_pct(r[2])} ({r[3]}/{r[4]}) |")
        out.append("")

    if "age_temp" in by_kind:
        out.append("### Age x temperature grid\n")
        out.append("| Age (y) | Temp (C) | Success |\n|---:|---:|---:|")
        for r in by_kind["age_temp"]:
            out.append(f"| {float(r[1]):.0f} | {float(r[2]):+.0f} | {fmt_pct(r[3])} |")
        out.append("")

    # Design sweep
    if "sweep" in by_kind:
        out.append("### Design sweep: code strength vs key length vs reliability\n")
        out.append("| t | k | blocks | secret bits | 85 C | age10@25C | age10@85C | age20@125C |")
        out.append("|---:|---:|---:|---:|---:|---:|---:|---:|")
        for r in by_kind["sweep"]:
            if len(r) < 9:
                continue
            out.append(f"| {r[1]} | {r[2]} | {r[3]} | {r[4]} | {fmt_pct(r[5])} | "
                       f"{fmt_pct(r[6])} | {fmt_pct(r[7])} | {fmt_pct(r[8])} |")
        out.append("")

    # Bounds
    if "bounds" in by_kind:
        out.append("### Reliability envelope per design point (enrolled new, 8 chips)\n")
        out.append("| t | secret bits | max temp (C) | max age (y) |")
        out.append("|---:|---:|---:|---:|")
        for r in by_kind["bounds"]:
            out.append(f"| {r[1]} | {r[2]} | {r[4]} | {r[5]} |")
        out.append("")

    # Baseline
    if "baseline" in by_kind:
        out.append("### Naive (no stability selection) vs stable-subset design\n")
        out.append("| Design | t | secret bits | 85 C | age10@25C | age20@25C | age10@85C |")
        out.append("|---|---:|---:|---:|---:|---:|---:|")
        for r in by_kind["baseline"]:
            out.append(f"| {r[1]} | {r[2]} | {r[3]} | {fmt_pct(r[4])} | {fmt_pct(r[5])} | "
                       f"{fmt_pct(r[6])} | {fmt_pct(r[7])} |")
        out.append("")

    # Envelope
    if "envelope" in by_kind:
        out.append("### Operating-envelope success (-20..70 C, 2.9..3.5 V, 0..10 y)\n")
        out.append("| t | secret bits | success rate | trials |")
        out.append("|---:|---:|---:|---:|")
        for r in by_kind["envelope"]:
            out.append(f"| {r[1]} | {r[2]} | {fmt_pct(r[3])} | {r[4]} |")
        out.append("")

    # Diagnostics
    if "volatile_recall" in by_kind:
        out.append("### Factory calibration captures later errors\n")
        if "volatile_fraction" in by_kind:
            vf = float(by_kind["volatile_fraction"][0][1])
            out.append(f"Volatile set = {100*vf:.1f}% of cells.\n")
        out.append("| Unlock temp (C) | Errors | In volatile set | Recall |")
        out.append("|---:|---:|---:|---:|")
        for r in by_kind["volatile_recall"]:
            # CSV: volatile_recall,<T>,<recall>,<hit>,<err>
            temp, rec, hit, err = float(r[1]), float(r[2]), r[3], r[4]
            out.append(f"| {temp:+.0f} | {err} | {hit} | {100*rec:.0f}% |")
        out.append("")

    if "naive_block_err" in by_kind:
        out.append("### Naive design: per-block hard-decision errors (t=32)\n")
        out.append("| Temp (C) | min | median | max |\n|---:|---:|---:|---:|")
        for r in by_kind["naive_block_err"]:
            out.append(f"| {float(r[1]):+.0f} | {r[2]} | {r[3]} | {r[4]} |")
        out.append("")

    if "extreme_temp" in by_kind:
        out.append("### Extreme temperature beyond rated envelope (t=32)\n")
        out.append("| Temp (C) | Success |\n|---:|---:|")
        for r in by_kind["extreme_temp"]:
            out.append(f"| {float(r[1]):+.0f} | {fmt_pct(r[2])} |")
        out.append("")

    if "extreme_age" in by_kind:
        out.append("### Extreme aging (25 C, t=32)\n")
        out.append("| Age (y) | Success |\n|---:|---:|")
        for r in by_kind["extreme_age"]:
            out.append(f"| {float(r[1]):.0f} | {fmt_pct(r[2])} |")
        out.append("")

    # Attacks
    out.append("### Attack results\n")
    out.append("| Attack | Result |")
    out.append("|---|---|")
    scalar = {}
    for kind in ("clone_accept", "tamper_false_accept", "lockout_attempts",
                 "ct_tamper_detected", "offline_guess_bits"):
        if kind in by_kind:
            scalar[kind] = by_kind[kind][0]
    if "clone_accept" in scalar:
        r = scalar["clone_accept"]
        out.append(f"| Clone flash onto foreign chips | {r[2]}/{r[3]} accepted |")
    if "tamper_false_accept" in scalar:
        r = scalar["tamper_false_accept"]
        out.append(f"| Single-bit helper tampering | {r[2]}/{r[3]} false accepts |")
    if "lockout_attempts" in scalar:
        out.append(f"| Ratchet lockout under tampering | locked after {scalar['lockout_attempts'][1]} attempts |")
    if "ct_tamper_detected" in scalar:
        out.append(f"| Ciphertext tamper | detected = {scalar['ct_tamper_detected'][1]} |")
    if "offline_guess_bits" in scalar:
        out.append(f"| Offline key-guess work bound | 2^{scalar['offline_guess_bits'][1]} |")
    out.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
